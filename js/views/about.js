// О проекте: как читать карту, пигменты эпох, источники и лицензии, куда копать дальше.
import { html, mount, safeUrl } from '../html.js';
import { RELATION, KIND, KIND_DESC, plural } from '../format.js?v=audit';
import { footer } from '../ui/common.js?v=audit-p1p2';

const REL_DESC = {
  evolved: 'Стиль прямо вырос из предшественника: те же мастера, школа или приёмы, доведённые до нового качества.',
  influence: 'Заметное влияние со стороны — как японская гравюра на импрессионистов.',
  reaction: 'Стиль возник в споре с предшественником, как его отрицание.',
  revival: 'Сознательное возрождение давнего стиля спустя века — неоготика, неоклассицизм, ретро-эстетики.',
};
const DASH = { evolved: '', influence: '2 0', reaction: '7 5', revival: '1.5 4.5' };
const WIDTH = { evolved: 2.2, influence: 1.2, reaction: 1.6, revival: 2.2 };

export default {
  render(root, { store }) {
    document.title = 'О проекте — Атлас эстетик';
    const imgs = store.styles.reduce((n, s) => n + (s.example.img ? 1 : 0) + s.gallery.filter((g) => g.img).length, 0);
    const fair = store.styles.reduce((n, s) => n + [s.example.img, ...s.gallery.map((g) => g.img)].filter((m) => m?.nonfree).length, 0);
    const total = store.styles.length;
    const reviewed = store.styles.filter((s) => s.review.status !== 'legacy').length;
    const rels = store.styles.flatMap((s) => s.parents);
    const verified = rels.filter((r) => r.status === 'verified').length;
    const cmp = store.styles.reduce((n, s) => n + s.comparisons.length, 0) / 2;
    const extracted = store.styles.filter((s) => s.palette?.source === 'image').length;

    mount(root, html`
    <article class="page about">
      <header class="about-head">
        <h1 class="about-title">О проекте</h1>
        <p class="about-lead">Атлас эстетик — навигатор по визуальным стилям, которые придумали люди: от наскальной живописи до интернет-эстетик 2020-х. Это не энциклопедия, а карта: она показывает, откуда стиль взялся, как его узнать и куда идти читать дальше.</p>
        <p class="about-lead">Атлас выборочный: ${total} ${plural(total, 'карточка', 'карточки', 'карточек')} не складываются в полную историю визуальных культур. Европа и XX век описаны подробнее, чем Африка, Южная и Восточная Азия, Америка до Колумба и Океания; одна обзорная карточка о целой цивилизации не равна десятку самостоятельных традиций.</p>
      </header>

      <section class="about-sec">
        <h2 class="section-title">Как читать карту</h2>
        <p>По горизонтали — время. Шкала неравномерная: каждая эпоха получает место по числу стилей, поэтому десятки тысяч лет первобытности и пятнадцать лет интернет-эстетик видны одинаково подробно. По вертикали — родословное древо: стиль стоит рядом со своим первым указанным предком, ветви расходятся вверх и вниз. Высота на карте не означает иерархию.</p>
        <p>Точка — начало стиля, цвет — эпоха. Длительность на карте не рисуется: годы есть в подписи при приближении и в карточке, а у выбранного стиля появляется полоса его жизни. Линия от точки — ствол, от которого отходят потомки; чем больше стилей выросло из линии, тем она толще — так видны главные маршруты истории. Карта больше экрана: её двигают перетаскиванием и колёсиком, миникарта в углу показывает, где вы, а «Вся история» вписывает всё целиком. Связь через века не тянется через всю карту, а показана двумя отростками с подписями «→ потомок» и «← предок»; целиком она появляется при наведении и выборе. Нажмите на стиль — его ближайшие связи откроются крупным планом, с названием типа связи; дальние родственники будут метками на краю экрана. «Вся родословная» показывает цепочку до истоков. Линии между стилями бывают четырёх видов:</p>
        <ul class="legend">
          ${Object.keys(RELATION).map((k) => html`<li>
            <svg viewBox="0 0 80 14" aria-hidden="true"><path d="M2 7 C 30 7, 50 7, 78 7" fill="none" stroke="currentColor" stroke-width="${WIDTH[k]}" stroke-dasharray="${DASH[k]}" stroke-linecap="round"/></svg>
            <span><strong>${RELATION[k].label[0].toUpperCase() + RELATION[k].label.slice(1)}.</strong> ${REL_DESC[k]}</span>
          </li>`)}
        </ul>
        <p>Отдельный слой карты — визуальные сопоставления: стили, похожие по виду, но без доказанной исторической связи. Их можно включить в легенде карты.</p>
      </section>

      <section class="about-sec">
        <h2 class="section-title">Насколько это проверено</h2>
        <p>Связи между стилями — редакционная схема. Из ${rels.length} ${plural(rels.length, 'связи', 'связей', 'связей')} источником подтверждены ${verified}; остальные помечены «не проверено» — это гипотеза, а не установленный факт. Первый предок в списке задаёт линию на карте, но не означает доказанную «главную линию».</p>
        <p>У ${reviewed} из ${total} карточек есть отметка о частичной или полной сверке с источниками. Её границы описаны на странице карточки; источники указаны у отдельных утверждений и подписей изображений. Остальные карточки — черновые. Визуальных сопоставлений пока ${cmp}.</p>
        <p>Автоматическая сборка проверяет структуру: что связи ведут к существующим карточкам, в родословной нет циклов, источники существуют, а ссылки открываются. Историческую истину и то, насколько картинка представляет стиль, она проверить не может — это работа редактора. Ссылки «Изучить дальше» — материалы для чтения, а не подтверждение каждого утверждения.</p>
        <p>Даты условны и значат разное: археологический возраст находок, периодизацию историков, годы существования группы или период популярности тренда. Где это важно, на странице карточки есть блок «Что значат даты». Даты до нашей эры записаны отрицательными годами; возраст «столько-то тысяч лет назад» переведён в календарный год приблизительно.</p>
      </section>

      <section class="about-sec">
        <h2 class="section-title">Что описывает карточка</h2>
        <p>Карточки описывают очень разные вещи, и у каждой указан тип:</p>
        <ul class="kind-list">
          ${Object.keys(KIND).map((k) => html`<li><strong>${KIND[k]}</strong> — ${KIND_DESC[k]}.</li>`)}
        </ul>
      </section>

      <section class="about-sec">
        <h2 class="section-title">Пигменты эпох</h2>
        <p>Каждой эпохе на карте и в хронологии соответствует цвет — пигмент или краска, которые её определяли.</p>
        <ol class="pigment-list">
          ${store.eras.map((e) => html`<li style="--c:var(--era-${e.id})"><span class="pl-chip"></span><span class="pl-name">${e.pigment}</span><span class="pl-era">${e.name}</span></li>`)}
        </ol>
      </section>

      <section class="about-sec">
        <h2 class="section-title">Откуда картинки</h2>
        <p>В атласе ${imgs} ${plural(imgs, 'изображение', 'изображения', 'изображений')}: материалы Wikimedia и собственные поясняющие схемы. Внешние изображения загружаются с серверов Wikimedia; рядом указаны сведения об авторе, лицензии файла и ссылка на его страницу. Лицензия фотографии относится к снимку: права на изображённое здание, скульптуру или плакат могут принадлежать другим.</p>
        <p>Собственные схемы созданы для атласа в 2026 году с помощью Codex. Они поясняют признаки стиля, а их подписи и ссылки на исходники позволяют отличить их от исторических работ.</p>
        <p>Если главная иллюстрация — не произведение своего времени, это подписано: «Предтеча», «Современная иллюстрация», «Реконструкция».</p>
        <p>${fair} ${plural(fair, 'изображение защищено', 'изображения защищены', 'изображений защищены')} авторским правом и помечены «несвободное». Их превью низкого разрешения взяты из английской Википедии. Википедия использует их по собственному обоснованию fair use, и оно не переносится автоматически на другие сайты: допустимость зависит от конкретного использования и юрисдикции. Под каждым таким изображением видно, проверено ли основание его использования в атласе. Если вы правообладатель, напишите в <a href="https://github.com/amchercashin/aesthetics-atlas/issues" target="_blank" rel="noopener">issues проекта</a> — мы заменим изображение ссылкой.</p>
        <p>Палитры бывают двух видов. «Цвета этого изображения» (${extracted} ${plural(extracted, 'карточка', 'карточки', 'карточек')}) — пять цветов, которые алгоритм нашёл на главной иллюстрации; это не палитра всего стиля. «Редакторская подборка» — цвета, подобранные вручную по признакам стиля. Они могут сопровождать схему или заменять отсутствующую иллюстрацию.</p>
        <p>Тексты описаний написаны для атласа и не копируют энциклопедии.</p>
      </section>

      ${store.resources.length ? html`<section class="about-sec">
        <h2 class="section-title">Копать дальше</h2>
        <p>Если хочется глубже — или в соседние области, которые атлас не охватывает: моду, кино, музыку, игры.</p>
        ${store.resources.map((g) => html`<h3 class="res-group">${g.group}</h3>
          <ul class="res-list">${g.items.map((r) => html`<li><a href="${safeUrl(r.url)}" target="_blank" rel="noopener">${r.title}</a><span>${r.note}${r.lang === 'ru' ? '' : ', на английском'}</span></li>`)}</ul>`)}
      </section>` : ''}

      <section class="about-sec">
        <h2 class="section-title">Предложить правку</h2>
        <p>Нашли ошибку, не хватает стиля или связи? Данные лежат в открытом репозитории в виде простых YAML-файлов — откройте issue или pull request на <a href="https://github.com/amchercashin/aesthetics-atlas" target="_blank" rel="noopener">GitHub</a>.</p>
      </section>
    </article>
    ${footer(store)}`);
  },
};
